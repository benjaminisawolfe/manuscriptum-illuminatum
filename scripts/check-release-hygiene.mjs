import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { inflateSync } from 'node:zlib';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { packages, collectFiles, isExcluded, readZipEntries } from './build-packages.mjs';

// Exceptions apply only to tooling terms, never credentials or excluded files.
// Each reviewed exception must name one exact package path, term, and reason.
export const toolingAllowlist = [];
const toolingPattern = /(?<![a-z0-9])(?:codex|openai|chatgpt|llms?)(?![a-z0-9])|large language models?|ai[- ]generated|generated by/gi;
const developmentName = /(?:^|[._-])(?:tasks?|handoff|qa|scratch|deployment[-_]notes|release[-_](?:audit|report)|content[-_]index[-_]regression|repository[-_]recovery|regression[-_]probes?)(?:[._-]|$)/i;
const additionalFiles = /^(?:package(?:-lock)?\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-lock\.yaml|storage[-_]state\.json|credentials\.json|cookies\.json|auth\.json|secrets\.json|\.npmrc|id_(?:rsa|ed25519|dsa|ecdsa)(?:\.pub)?|playwright\.config\.[cm]?[jt]s)$/i;
const rules = [
    ['workstation-path', /(?<![a-z0-9])(?:[a-z]:[\\/]+[a-z0-9_. -]+|\/(?:home|Users)\/[a-z0-9_.-]+)/gi],
    ['internal-path', /playwright[\\/]\.auth|(?:^|[\\/])(?:\.cache|\.auth|test-results|playwright-report)(?:[\\/]|$)/gim],
    ['internal-process', /mi-(?:listing|runtime)-regression-probes?|register_persistence_probe_route|rest_bootstrap_probe|rest_probe_(?:response|write)_data|character-publication\/persistence-probe|player-access\/(?:bootstrap-probe|status)|guarded test probe|guarded diagnostics for integration tests|internal QA notes|repository[- ]recovery|ars-magica-theme/gi],
    ['private-key', /-----BEGIN (?:(?:(?:RSA|EC|DSA|OPENSSH|ENCRYPTED) )?PRIVATE KEY|PGP PRIVATE KEY BLOCK)-----/g],
    ['credential-literal', /\b(?:password|passwd|pwd|api[_-]?key|access[_-]?token|auth[_-]?token|client[_-]?secret|secret[_-]?key|authorization|cookie)\b['"]?\s*(?:=>|[:=])\s*['"][^'"\r\n]+['"]/gi],
    ['long-secret-literal', /\b(?:token|secret)\b['"]?\s*(?:=>|[:=])\s*['"][^'"\r\n]{20,}['"]/gi],
    ['wordpress-secret', /\bdefine\s*\(\s*['"](?:AUTH|SECURE_AUTH|LOGGED_IN|NONCE)_(?:KEY|SALT)['"]\s*,\s*['"][^'"\r\n]+['"]/g],
    ['provider-token', /\b(?:gh[pousr]_[a-z0-9]{30,}|github_pat_[a-z0-9_]{40,}|sk-(?:proj-)?[a-z0-9_-]{20,}|AKIA[0-9A-Z]{16}|xox[baprs]-[a-z0-9-]{20,})\b/gi],
    ['authorization-token', /\bBearer\s+[a-z0-9._~-]{20,}|https?:\/\/[^/\s:@]+:[^/\s@]+@/gi],
    ['authentication-state', /["']cookies["']\s*:\s*\[|["']name["']\s*:\s*["']wordpress_(?:logged_in|sec)_/gi],
];
const printableStrings = content => (content.toString('latin1').match(/[\x20-\x7e]{8,}/g) || []).join('\n');

// Compressed image pixels are not text. Inspect embedded PNG text/EXIF metadata
// instead, including compressed and international text chunks.
export function inspectableText(content) {
    if (content.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) {
        const text = [];
        let offset = 8;
        while (offset < content.length) {
            if (offset + 12 > content.length) throw new Error('Truncated PNG metadata');
            const length = content.readUInt32BE(offset);
            const type = content.toString('ascii', offset + 4, offset + 8);
            if (offset + 12 + length > content.length) throw new Error('Truncated PNG chunk');
            const data = content.subarray(offset + 8, offset + 8 + length);
            if (type === 'tEXt') text.push(data.toString('utf8').replaceAll('\0', '\n'));
            if (type === 'zTXt' || type === 'iTXt') {
                const keywordEnd = data.indexOf(0);
                if (keywordEnd < 0) throw new Error('Malformed PNG text chunk');
                text.push(data.subarray(0, keywordEnd).toString('utf8'));
                let start = keywordEnd + 2;
                let compressed = true;
                if (type === 'iTXt') {
                    compressed = data[keywordEnd + 1] === 1;
                    start = keywordEnd + 3;
                    for (let field = 0; field < 2; field++) {
                        const end = data.indexOf(0, start);
                        if (end < 0) throw new Error('Malformed PNG international text');
                        text.push(data.subarray(start, end).toString('utf8'));
                        start = end + 1;
                    }
                }
                const payload = data.subarray(start);
                text.push((compressed ? inflateSync(payload, { maxOutputLength: 8 * 1024 * 1024 }) : payload).toString('utf8'));
            }
            if (type === 'eXIf') text.push(printableStrings(data));
            offset += 12 + length;
        }
        return text.join('\n');
    }
    if (content[0] === 0xff && content[1] === 0xfe) return content.subarray(2).toString('utf16le');
    if (content[0] === 0xfe && content[1] === 0xff) return Buffer.from(content.subarray(2)).swap16().toString('utf16le');
    return content.includes(0) ? printableStrings(content) : content.toString('utf8');
}

export function scanEntry({ name, content }, allowlist = toolingAllowlist) {
    for (const item of allowlist) {
        if (!item.path || !item.term || typeof item.reason !== 'string' || !item.reason.trim()) {
            throw new Error('Tooling allowlist entries require an exact path, term, and explanation');
        }
    }
    const findings = [];
    const normalized = name.replaceAll('\\', '/');
    const basename = normalized.split('/').at(-1);
    if (normalized.startsWith('/') || /^[a-z]:/i.test(normalized) || normalized.split('/').some(part => part === '..' || part === '.')) {
        findings.push({ file: name, rule: 'unsafe-path' });
    }
    if (isExcluded(normalized) || normalized.split('/').some(part => developmentName.test(part)) || additionalFiles.test(basename)
        || /\.(?:spec|test)\.[cm]?[jt]sx?$/i.test(basename)
        || normalized.split('/').some(part => /^(?:\.codex|\.agents|\.ssh|\.aws|scripts|packages|qa|scratch)$/i.test(part))) {
        findings.push({ file: name, rule: 'development-file' });
    }
    const text = inspectableText(content);
    for (const [location, value] of [['filename', normalized], ['content', text]]) {
        for (const match of value.matchAll(new RegExp(toolingPattern))) {
            if (!allowlist.some(item => item.path === normalized && item.term.toLowerCase() === match[0].toLowerCase())) {
                findings.push({ file: name, rule: 'tooling-reference', location, line: value.slice(0, match.index).split('\n').length });
            }
        }
    }
    for (const [rule, pattern] of rules) {
        for (const match of text.matchAll(new RegExp(pattern))) {
            findings.push({ file: name, rule, line: text.slice(0, match.index).split('\n').length });
        }
    }
    // Never include the matching content: diagnostics must not echo secrets.
    return findings;
}

export async function auditPackage(definition, allowlist = toolingAllowlist) {
    const source = new Map();
    const findings = [];
    for (const file of await collectFiles(definition.source)) {
        const entry = { name: definition.root + '/' + file.archivePath, content: await readFile(file.absolutePath) };
        source.set(entry.name, entry.content);
        findings.push(...scanEntry(entry, allowlist).map(item => ({ ...item, surface: 'source' })));
    }
    const bytes = await readFile(definition.archive);
    const entries = readZipEntries(bytes);
    const seen = new Set();
    for (const entry of entries) {
        findings.push(...scanEntry(entry, allowlist).map(item => ({ ...item, surface: 'zip' })));
        if (seen.has(entry.name)) findings.push({ file: entry.name, surface: 'zip', rule: 'duplicate-entry' });
        seen.add(entry.name);
        const expected = source.get(entry.name);
        if (!expected || !expected.equals(entry.content)) findings.push({ file: entry.name, surface: 'zip', rule: 'source-mismatch' });
    }
    for (const name of source.keys()) {
        if (!seen.has(name)) findings.push({ file: name, surface: 'zip', rule: 'missing-source-file' });
    }
    if (!entries.length || !source.size) findings.push({ file: definition.root, rule: 'empty-package' });
    return {
        archive: path.basename(definition.archive),
        bytes: bytes.length,
        files: entries.length,
        sha256: createHash('sha256').update(bytes).digest('hex'),
        fileList: entries.map(entry => entry.name),
        findings,
    };
}

async function main() {
    const reports = [];
    for (const definition of packages) reports.push(await auditPackage(definition));
    const failures = reports.flatMap(report => report.findings.map(finding => ({ archive: report.archive, ...finding })));
    if (process.argv.includes('--json')) {
        process.stdout.write(JSON.stringify(reports, null, 2) + '\n');
    } else {
        for (const report of reports) {
            process.stdout.write(report.archive + ': ' + report.files + ' files, ' + report.bytes + ' bytes, SHA-256 ' + report.sha256 + '\n');
            if (process.argv.includes('--list')) for (const name of report.fileList) process.stdout.write('  ' + name + '\n');
        }
        for (const finding of failures) {
            process.stderr.write(finding.archive + ' [' + (finding.surface || 'zip') + '] ' + finding.file
                + (finding.line ? ':' + finding.line : '') + ' — ' + finding.rule + '\n');
        }
        process.stdout.write(failures.length ? 'Release hygiene FAILED.\n' : 'Release hygiene passed: runtime source and ZIP contents match and contain no prohibited artifacts.\n');
    }
    if (failures.length) process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main().catch(error => { process.stderr.write('Release hygiene failed: ' + error.message + '\n'); process.exitCode = 1; });
}
